"""User-declared direct tasks; no keyword classifier or model planning call.

Old/unspecified routes remain team workflows. Direct mode is available only for
one explicit, independent, low-complexity contract and retains every downstream
permission, host-check, review, and delivery gate.
"""
import copy
import json
import math
import re


VERSION = 1
MODULE_ID = 'direct-task'
WORK_TYPES = {'development', 'research', 'writing', 'design', 'data', 'general', 'image'}
CAPABILITIES = {'text', 'workspace', 'files', 'terminal', 'web_search', 'browser', 'plugins', 'image'}
SKILLS = {'planning', 'coding', 'review', 'visual', 'reasoning', 'writing', 'image'}
TEMPLATES = {
    'development': {'coding': .75, 'reasoning': .25},
    'research': {'reasoning': .6, 'writing': .4},
    'writing': {'writing': 1}, 'design': {'visual': .6, 'writing': .4},
    'data': {'reasoning': .6, 'coding': .4}, 'general': {'reasoning': .5, 'writing': .5},
}


def normalize_route(raw=None, request=''):
    """Normalize a new user selection; reason is always generated by the host."""
    from project_team import SECRET
    if SECRET.search(json.dumps({'route': raw, 'request': request}, ensure_ascii=False)):
        raise ValueError('任务路由或执行说明包含凭据，已拒绝保存，请先移除')
    if raw is None:
        return {'mode': 'team'}
    if not isinstance(raw, dict) or set(raw) - {'mode', 'contract', 'reason'}:
        raise ValueError('任务路由只接受mode与明确的单模块contract')
    mode = raw.get('mode', 'team')
    if mode not in ('team', 'direct'):
        raise ValueError('任务路由须为team或direct')
    if mode == 'team':
        if 'contract' in raw:
            raise ValueError('小组路由不接收独立合同；请将必要约束写入任务正文')
        return {'mode': 'team'}
    contract = raw.get('contract')
    if contract is None:
        raise ValueError('独立任务须提供完整单模块合同；请补齐或明确改选小组规划')
    fields = {'roleId', 'roleType', 'workType', 'instructions', 'scope', 'acceptance', 'skills',
              'requiredCapabilities', 'complexity', 'dependsOn', 'reviewRequirements', 'processRequirements'}
    if not isinstance(contract, dict) or set(contract) - fields:
        raise ValueError('独立任务合同包含未支持的字段，不能指定模型或自行授予工具')
    if any(not contract.get(key) for key in ('roleId', 'workType', 'scope', 'acceptance')):
        raise ValueError('请完整指定岗位、工作类型、交付范围与验收标准，或明确改选小组规划')
    role = contract['roleId']
    if (not isinstance(role, str) or not re.fullmatch(r'[a-z][a-z0-9_-]{0,47}', role)
            or role in ('coordinator', 'reviewer') or role.startswith('reviewer-')):
        raise ValueError('独立任务须选择合法执行岗位，不能使用主负责人或复核者岗位')
    from project_team import ROLE_SPECS
    role_type = contract.get('roleType')
    if role_type is not None and (not isinstance(role_type, str) or role_type not in ROLE_SPECS or role_type == 'coordinator'):
        raise ValueError('独立任务基础岗位类型无效')
    work_type = contract['workType']
    if not isinstance(work_type, str) or work_type not in WORK_TYPES:
        raise ValueError('独立任务工作类型无效')
    complexity = contract.get('complexity', 2)
    if type(complexity) is not int or complexity < 1:
        raise ValueError('任务复杂度须为正整数')
    if complexity > 2:
        raise ValueError('复杂度超过2不能直接分派，请明确改选小组规划')
    dependencies = contract.get('dependsOn', [])
    if not isinstance(dependencies, list) or any(not isinstance(item, str) or not item for item in dependencies):
        raise ValueError('任务依赖须为模块编号列表')
    if dependencies:
        raise ValueError('存在其他模块依赖，不能直接分派，请明确改选小组规划')
    scopes, acceptance = contract['scope'], contract['acceptance']
    if (not isinstance(scopes, list) or not 1 <= len(scopes) <= 12
            or any(not isinstance(path, str) or not path for path in scopes)):
        raise ValueError('交付范围须为1–12项相对文件或目录')
    from studio import clean_path
    normalized_paths = []
    for path in scopes:
        clean_path(path.rstrip('/'))
        key = path.rstrip('/').casefold()
        if any(key == old or key.startswith(old + '/') or old.startswith(key + '/') for old in normalized_paths):
            raise ValueError('独立任务交付范围不能重复或互相覆盖')
        normalized_paths.append(key)
    if (not isinstance(acceptance, list) or not 1 <= len(acceptance) <= 12
            or any(not isinstance(item, str) or not item.strip() or len(item) > 4000 for item in acceptance)
            or len(set(acceptance)) != len(acceptance)):
        raise ValueError('验收标准须为1–12条不重复的明确文本')
    instructions = contract.get('instructions')
    if instructions is None or instructions == '':
        instructions = request
    if not isinstance(instructions, str):
        raise ValueError('独立任务执行说明须为文本')
    if not instructions.strip():
        raise ValueError('缺少明确执行说明，请补齐或明确改选小组规划')
    if len(instructions) > 32000:
        raise ValueError('独立任务执行说明过长')
    capabilities = contract.get('requiredCapabilities', ['text'])
    if (not isinstance(capabilities, list) or not capabilities
            or any(not isinstance(item, str) or item not in CAPABILITIES for item in capabilities)
            or len(set(capabilities)) != len(capabilities)):
        raise ValueError('独立任务能力列表无效')
    if 'workspace' in capabilities and set(capabilities) - {'text', 'workspace'}:
        raise ValueError('workspace不能与其他工具引擎混为同一模块')
    if work_type == 'image' or set(capabilities) - {'text', 'workspace'}:
        raise ValueError('当前独立任务只支持text/workspace，请明确改选小组规划')
    skills = contract.get('skills', TEMPLATES[work_type])
    if (not isinstance(skills, dict) or not skills or any(key not in SKILLS or type(value) not in (int, float)
            or not math.isfinite(value) or not 0 <= value <= 1 for key, value in skills.items())
            or not sum(skills.values()) or skills.get('image', 0) > 0):
        raise ValueError('独立任务能力权重须为有效的0–1文字任务先验')
    ids = [MODULE_ID + '-c' + str(i + 1) for i in range(len(acceptance))]
    from review_requirements import _promise, validate_module_requirements
    explicit = contract.get('reviewRequirements')
    if explicit is not None and not isinstance(explicit, dict):
        raise ValueError('独立任务复核要求须为结构化对象')
    if explicit is not None:
        validate_module_requirements({'id': MODULE_ID, 'acceptance': acceptance, 'instructions': instructions,
                                      'workType': work_type, 'requiredCapabilities': capabilities,
                                      'reviewRequirements': explicit})
    if work_type == 'development':
        if explicit is not None and explicit.get('mode') != 'independent':
            raise ValueError('开发独立任务须安排独立产物复核，不能降级为无复核')
        requirement = {'mode': 'independent', 'criterionIds': ids, 'reason': '用户直接路由的开发模块须独立复核全部固定标准'}
    elif explicit is not None:
        requirement = copy.deepcopy(explicit)
    elif any(_promise(item) for item in [instructions, *acceptance]):
        requirement = {'mode': 'independent', 'criterionIds': ids, 'reason': '保留明确文本中的独立产物复核义务'}
    else:
        requirement = {'mode': 'none', 'criterionIds': [], 'reason': '用户未新增独立产物复核义务，仍需原有质量验收'}
    normalized = {'roleId': role, 'workType': work_type, 'instructions': instructions,
                  'scope': list(scopes), 'acceptance': list(acceptance), 'skills': copy.deepcopy(skills),
                  'requiredCapabilities': list(capabilities), 'complexity': complexity, 'reviewRequirements': requirement}
    if 'processRequirements' in contract:
        from worker_process_policy import normalize_requirements
        process=normalize_requirements(contract['processRequirements'])
        if process is None or 'workspace' not in capabilities:
            raise ValueError('明确必做过程必须绑定workspace；未启用则省略processRequirements')
        normalized['processRequirements']=process
    if role_type is not None:
        normalized['roleType'] = role_type
    validate_module_requirements({'id': MODULE_ID, **normalized})
    return {'mode': 'direct', 'contract': normalized}


def direct_plan(run):
    """Construct one host plan from a frozen direct contract; select no model."""
    route = run.get('taskRouting') or {'mode': 'team'}
    if not isinstance(route, dict):
        raise ValueError('本轮任务路由格式无效')
    if route.get('mode') == 'team':
        return None
    if type(run.get('taskRoutingVersion')) is not int or run['taskRoutingVersion'] != VERSION:
        raise ValueError('独立路由缺少本轮冻结的版本，不能补写历史')
    normalized = normalize_route(route, run.get('request', ''))
    if normalized != route or normalized['mode'] != 'direct':
        raise ValueError('独立任务合同与本轮冻结路由不一致，不能在恢复时改写')
    module = {'id': MODULE_ID, 'title': '明确独立任务 · ' + route['contract']['roleId'],
              'priority': 'P1', 'dependsOn': [], **copy.deepcopy(route['contract'])}
    return {'summary': '用户已明确单模块合同，由宿主规则路由直接分派，不调用模型生成初始规划。',
            'businessUnderstanding': '只依据本轮冻结项目资料、任务说明和用户给出的范围与标准执行；未提供的事实保持未知。',
            'modules': [module], 'integration': '仍须执行已登记宿主验收、已冻结产物复核及主负责人最终质量关卡，全部通过后才可合入。',
            'risks': [], 'blockingQuestions': []}
